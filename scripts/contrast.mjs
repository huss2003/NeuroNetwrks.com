// Reads colour tokens from src/styles/global.css, checks the text/background
// pairs the site uses against WCAG 2.2 AA, writes docs/contrast-report.md and
// exits non-zero if any required pair fails.
import { readFileSync, writeFileSync } from 'node:fs';

const css = readFileSync('src/styles/global.css', 'utf8');
const tokens = Object.fromEntries(
  [...css.matchAll(/--color-([a-z0-9-]+):\s*(#[0-9a-fA-F]{6})/g)].map((m) => [m[1], m[2]]),
);

const lin = (c) => {
  const v = c / 255;
  return v <= 0.04045 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4;
};
const lum = (hex) => {
  const n = parseInt(hex.slice(1), 16);
  return 0.2126 * lin((n >> 16) & 255) + 0.7152 * lin((n >> 8) & 255) + 0.0722 * lin(n & 255);
};
const ratio = (a, b) => {
  const [hi, lo] = [lum(a), lum(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
};

// [foreground, background, minimum ratio, use]
const pairs = [
  ['ink', 'bg', 4.5, 'Body text on white'],
  ['ink', 'bg-soft', 4.5, 'Body text on soft background'],
  ['slate', 'bg', 4.5, 'Secondary text on white'],
  ['slate', 'bg-soft', 4.5, 'Secondary text on soft background'],
  ['blue-700', 'bg', 4.5, 'Links on white'],
  ['blue-700', 'bg-soft', 4.5, 'Links on soft background'],
  ['blue-600', 'bg', 4.5, 'Brand blue as text on white'],
  ['bg', 'blue-600', 4.5, 'White text on primary button'],
  ['bg', 'blue-700', 4.5, 'White text on hovered button'],
  ['bg', 'blue-900', 4.5, 'White text on dark blue band'],
  ['ink', 'green-600', 4.5, 'Ink text on green fill'],
  ['green-700', 'bg', 4.5, 'Green text on white'],
  ['green-700', 'green-50', 4.5, 'Green text on green tint'],
  ['ink', 'blue-50', 4.5, 'Ink on blue tint'],
  ['ink', 'blue-100', 4.5, 'Ink on selection'],
  [
    'green-600',
    'bg',
    3,
    'INFO: green marks on white are decorative only (2.6:1); never carry meaning by green alone, pair with text or ink',
  ],
  ['blue-600', 'bg', 3, 'Focus ring on white (non-text, 3:1)'],
  ['line', 'bg', 1, 'Hairline rules (decorative, informational only)'],
  ['green-600', 'bg', 4.5, 'INFO: brand green as text on white (expected to fail, never used)'],
];

let failed = 0;
const rows = pairs.map(([fg, bg, min, use]) => {
  const r = ratio(tokens[fg], tokens[bg]);
  const info = use.startsWith('INFO');
  const ok = r >= min;
  if (!ok && !info) failed++;
  return `| ${use} | ${fg} ${tokens[fg]} | ${bg} ${tokens[bg]} | ${r.toFixed(2)}:1 | ${min}:1 | ${info ? 'n/a' : ok ? 'pass' : 'FAIL'} |`;
});

const report = `# Contrast report

Generated by \`node scripts/contrast.mjs\` from \`src/styles/global.css\`. WCAG 2.2 AA: 4.5:1 for text, 3:1 for non-text marks.

| Use | Foreground | Background | Ratio | Needs | Result |
|---|---|---|---|---|---|
${rows.join('\n')}
`;
writeFileSync('docs/contrast-report.md', report);
console.log(report);
if (failed) {
  console.error(`${failed} required pair(s) failed.`);
  process.exit(1);
}
